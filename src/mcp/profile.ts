import { lstat, readFile, realpath } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export interface ProfileDiagnostic {
  ruleId: "MINA-MCP-PROFILE-001" | "MINA-MCP-PROFILE-002";
  severity: "error";
  message: string;
}

export interface McpProfileReport {
  safe: boolean;
  profile: string;
  command: unknown;
  args: unknown;
  diagnostics: ProfileDiagnostic[];
}

interface GeneratedProfile {
  mcpServers: {
    minaSafe: {
      command: string;
      args: string[];
    };
  };
}

export async function generateMcpProfile(): Promise<GeneratedProfile> {
  const command = await canonicalRegularFile("/usr/bin/env", "system environment launcher");
  const node = await canonicalRegularFile(process.execPath, "Node executable");
  const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  const launcher = await canonicalRegularFile(
    resolve(packageRoot, "dist/mcp/launch-readonly.js"),
    "compiled Mina MCP policy launcher",
  );
  return {
    mcpServers: {
      minaSafe: {
        command,
        args: ["-i", node, launcher],
      },
    },
  };
}

export async function checkMcpProfile(profilePath: string): Promise<McpProfileReport> {
  const resolvedProfile = resolve(profilePath);
  const value: unknown = JSON.parse(await readFile(resolvedProfile, "utf8"));
  const root = asRecord(value);
  const servers = asRecord(root?.mcpServers);
  const server = asRecord(servers?.minaSafe);
  const command = server?.command;
  const args = server?.args;
  const diagnostics: ProfileDiagnostic[] = [];
  const expected = await generateMcpProfile();
  const expectedServer = expected.mcpServers.minaSafe;

  if (command !== expectedServer.command || !arraysEqual(args, expectedServer.args)) {
    diagnostics.push({
      ruleId: "MINA-MCP-PROFILE-001",
      severity: "error",
      message:
        "Profile must use the canonical installation-specific launcher generated by 'profile generate'.",
    });
  }

  const rootKeys = root ? Object.keys(root) : [];
  const serverNames = servers ? Object.keys(servers) : [];
  const serverKeys = server ? Object.keys(server) : [];
  if (
    !root ||
    rootKeys.some((key) => !["$schema", "mcpServers"].includes(key)) ||
    !servers ||
    serverNames.length !== 1 ||
    serverNames[0] !== "minaSafe" ||
    !server ||
    serverKeys.length !== 2 ||
    serverKeys.some((key) => !["command", "args"].includes(key))
  ) {
    diagnostics.push({
      ruleId: "MINA-MCP-PROFILE-002",
      severity: "error",
      message:
        "Profile must contain only the generated minaSafe launcher with no overrides or sibling servers.",
    });
  }

  return {
    safe: diagnostics.length === 0,
    profile: resolvedProfile,
    command,
    args,
    diagnostics,
  };
}

async function canonicalRegularFile(path: string, label: string): Promise<string> {
  const metadata = await lstat(path);
  if (!metadata.isFile() || metadata.isSymbolicLink()) {
    throw new Error(`${label} must be a regular file, not a symlink.`);
  }
  return realpath(path);
}

function arraysEqual(value: unknown, expected: string[]): boolean {
  return (
    Array.isArray(value) &&
    value.every((item) => typeof item === "string") &&
    JSON.stringify(value) === JSON.stringify(expected)
  );
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined;
  return value as Record<string, unknown>;
}
